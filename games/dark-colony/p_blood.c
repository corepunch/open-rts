/* 0x4385a8 / 0x438df2: exact type-prefix lookup in the common FIN label
 * namespace, probing even numeric facings and packing only families A-G. */
int P_DC_BloodStates(uint16_t native_type, int out[7]) {
    if (native_type >= GAMESTAT_UNIT_COUNT) return 0;
    int count = 0;
    for (char family = 'A'; family <= 'G'; ++family) {
        int state = S_NULL;
        for (int facing = 0; facing < 32 && !state; facing += 2) {
            char name[64];
            snprintf(name, sizeof(name), "%sBLOOD%c%d",
                     dc_gamestat_units[native_type].sprite, family, facing);
            for (size_t i = 0; i < sizeof(blood_labels) / sizeof(*blood_labels); ++i)
                if (!strcmp(name, blood_labels[i].name)) { state = blood_labels[i].state; break; }
        }
        if (state) out[count++] = state;
    }
    return count;
}

void A_DC_Damage(mobj_t *target) {
    A_DC_BuildingStand(target);
    if (P_MobjIsHidden(target)) return;
    int variants[7];
    int count = P_DC_BloodStates(target->native_type_id, variants);
    if (!count) return;
    int first = variants[P_DC_Random() % count];
    mobj_t *blood = P_SpawnMobj(target->core.position, MT_BLOOD);
    if (!blood) return;
    blood->core.angle = target->core.angle;
    blood->team = target->team;
    blood->core.render_offset = target->core.render_offset;
    /* 0x423c34 resets frame/timer to zero; 0x423dd0 advances to +1
     * before loading the first delay. A one-frame label ends immediately. */
    P_SetMobjState(blood, gameinfo->states[first].nextstate);
}
