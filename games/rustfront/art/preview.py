#!/usr/bin/env python3
"""Renders prefabs in the game's view and light, one picture each, for checking art while it is
being made. It reads the live art/prefabs and never touches art/.build or art/previews.

    python3 games/rustfront/art/preview.py --out /tmp/look clans/trike clans/hall
    python3 games/rustfront/art/preview.py --out /tmp/look --scale 0.6 infantry/rifleman:30:Ready infantry/rifleman:90:Dead

A spec is prefab[:yaw[:pose]]. yaw turns it about the vertical (degrees; vehicles face +X, so
-45 shows their front three-quarter as the sprites do; default 0, or -45 under vehicles/ and
in a path holding a vehicle). pose plays one of a character's poses, or a clip at its start
with @Clip. Characters (prefabs with up="z") are stood up as sprites.py does. Each spec gets
<out>/<n>_<prefab name>.png at --scale cm per pixel (1.5, like the previews; 0.6 suits
soldiers), framed --size W H pixels around --look cm above the ground; <out>/all.png shows
every spec side by side.
"""
import argparse
import math
import re
import subprocess
import sys
from pathlib import Path

ART = Path(__file__).resolve().parent
sys.path.insert(0, str(ART))
import layout as L  # noqa: E402

SCENER = "scener"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--scale", type=float, default=L.CM_PER_PX, help="cm per pixel")
    ap.add_argument("--size", type=int, nargs=2, default=(512, 448), metavar=("W", "H"))
    ap.add_argument("--look", type=float, default=90.0, help="cm above the ground at the frame centre")
    ap.add_argument("--team", default=L.TEAM, help='team colour, "r g b" (default the blue)')
    ap.add_argument("specs", nargs="+")
    a = ap.parse_args()

    out = a.out.resolve()
    work = out / "work"
    work.mkdir(parents=True, exist_ok=True)
    for name in ("prefabs", "kit.xml", "utilities.xml"):   # live links: includes resolve as in art/
        link = work / name
        if not link.is_symlink():
            link.symlink_to(ART / name)

    to_cam = L.unit(L.YAW, L.ELEV)
    w, h = a.size
    spacing = max(w, h) * a.scale * 1.6
    insts, cams = [], []
    for i, spec in enumerate(a.specs):
        parts = spec.split(":")
        src = parts[0]
        path = ART / "prefabs" / (src + ".blk")
        if not path.exists():
            sys.exit("preview.py: no prefab %s" % path)
        text = path.read_text()
        vehicle = "vehicles/" in src or "/vehicle" in src
        yaw = float(parts[1]) if len(parts) > 1 and parts[1] else (-45.0 if vehicle else 0.0)
        child = ""
        if len(parts) > 2 and parts[2]:
            child = '<layer clip="%s"/>' % parts[2][1:] if parts[2].startswith("@") else '<layer pose="%s"/>' % parts[2]
        x = i * spacing
        root = re.search(r"<prefab\b[^>]*>", re.sub(r"<!--.*?-->", "", text, flags=re.S))
        rot = '-90 %g 0' % (yaw + 90) if root and 'up="z"' in root.group(0) else '0 %g 0' % yaw
        name = "p%02d" % i
        insts.append('  <prefab source="%s" name="%s" pos="%.1f 0 0" rot="%s" color="%s">%s</prefab>'
                     % (src, name, x, rot, a.team, child))
        look = (x, a.look, 0.0)
        pos = [look[k] + 4000 * to_cam[k] for k in range(3)]
        cams.append('  <camera name="%02d_%s" pos="%s" look="%s" ortho="%g" size="%d %d"/>'
                    % (i, src.replace("/", "_"), " ".join("%.1f" % c for c in pos),
                       " ".join("%.1f" % c for c in look), h * a.scale, w, h))
    n = len(a.specs)
    mid = ((n - 1) * spacing / 2, a.look, 0.0)
    pos = [mid[k] + 4000 * to_cam[k] for k in range(3)]
    cams.append('  <camera name="all" pos="%s" look="%s" ortho="%g" size="%d %d"/>'
                % (" ".join("%.1f" % c for c in pos), " ".join("%.1f" % c for c in mid),
                   h * a.scale, int(w * (1 + (n - 1) * spacing / (w * a.scale)) // 8 * 8), h))
    scene = work / "preview.blks"
    scene.write_text('<?xml version="1.0" encoding="UTF-8"?>\n<!-- GENERATED by preview.py -->\n'
                     '<scene %s background="0.30 0.27 0.23">\n%s\n\n%s\n\n%s\n'
                     '  <box name="ground" size="200000 10 20000" pos="0 -5 0" material="sand"/>\n%s\n</scene>\n'
                     % (L.SCENE_ATTRS, L.PALETTE.replace("{TEAM}", a.team), L.LIGHTS,
                        "\n".join(cams), "\n".join(insts)))
    r = subprocess.run([SCENER, "--render", str(scene), "--format", "png", "--output-dir", str(out),
                        "--supersample", "2"], capture_output=True, text=True)
    if r.returncode:
        sys.exit("scener failed:\n" + (r.stderr or r.stdout)[-3000:])
    warn = [l for l in (r.stderr + r.stdout).splitlines()
            if l.startswith(("warning", "error")) and "z-fight" not in l]
    if warn:
        print("\n".join(warn[:30]))
    print("wrote %d pictures and all.png into %s" % (n, out))


if __name__ == "__main__":
    main()
