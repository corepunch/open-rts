#!/usr/bin/env python3
"""Renders Rustfront's interface skins with Scener: games/rustfront/sprites/ui.png and ui.json.

    python3 games/rustfront/art/ui.py

The interface is metal: a heavy panel plate behind the sidebar and the front end's pages,
recessed screens behind the radar, the credits and the build list, and buttons in four states
(normal, focus, pressed, disabled). Each is a prefab in prefabs/ui/ seen straight on, lit from
the top left, at 1 cm a pixel, which is the interface's size in a window at twice its 640 x 480
layout. The game draws them as nine-slices (hud/m_menu.c M_DrawNineSlice): the outer `slice`
pixels keep their size and the middle stretches, so one picture fits any rectangle.
art/pack8.py maps the sheet onto the game palette (assets/ui.pcx) and writes its table into
sprites.inc (RF_UI_*).
"""
import json
import re
import subprocess
import sys
from pathlib import Path

from PIL import Image

ART = Path(__file__).resolve().parent
sys.path.insert(0, str(ART))
import sprites as S  # noqa: E402

SUPERSAMPLE = 4
# name, prefab, size (px = cm), slice (px), knobs
PARTS = [
    ("panel", "ui/panel", (160, 160), 14, {}),
    ("well", "ui/well", (64, 64), 8, {}),
    ("button", "ui/button", (96, 40), 9, {"state": 0}),
    ("button_focus", "ui/button", (96, 40), 9, {"state": 1}),
    ("button_pressed", "ui/button", (96, 40), 9, {"state": 2}),
    ("button_disabled", "ui/button", (96, 40), 9, {"state": 3}),
]
SPACING = 1000.0
LIGHTS = """  <!-- an interface lit from the top left and in front, as bevels are drawn -->
  <sun dir="0.55 -0.65 -1.0" color="1.0 0.96 0.90" intensity="1.15" castShadows="1"/>
  <sun dir="-0.4 0.3 -1.0" color="0.75 0.85 1.0" intensity="0.18" castShadows="0"/>"""


def materials():
    text = (ART / "prefabs" / "ui" / "materials.xml").read_text()
    return re.search(r"<library>(.*)</library>", text, re.S).group(1)


def variant(prefab, name, knobs, size):
    """A copy of the prefab with its size and knobs set, in the build folder."""
    text = (ART / "prefabs" / (prefab + ".blk")).read_text()
    values = dict(knobs, w=size[0], h=size[1])
    for k, v in values.items():
        text, hits = re.subn(r'(<let name="%s" value=")[^"]*(")' % k, r"\g<1>%s\g<2>" % v, text)
        if hits != 1:
            sys.exit("ui.py: %s.blk has no <let name=\"%s\"> knob" % (prefab, k))
    out = S.WORK / "prefabs" / (prefab + "@" + name + ".blk")
    out.write_text(text)
    return prefab + "@" + name


def main():
    S.prepare_work()
    insts, cams = [], []
    for i, (name, prefab, size, _, knobs) in enumerate(PARTS):
        src = variant(prefab, name, knobs, size)
        x = i * SPACING
        insts.append('  <prefab source="%s" name="ui_%s" pos="%.1f 0 0"/>' % (src, name, x))
        cams.append('  <camera name="%s" pos="%.1f 0 2000" look="%.1f 0 0" ortho="%d" size="%d %d"/>'
                    % (name, x, x, size[1], size[0] * SUPERSAMPLE, size[1] * SUPERSAMPLE))
    scene = S.WORK / "ui.blks"
    scene.write_text('<?xml version="1.0" encoding="UTF-8"?>\n<!-- GENERATED by ui.py -->\n'
                     '<scene ambient="0.30 0.30 0.31" skyReflection="0.5" background="0 0 0">\n%s\n%s\n\n%s\n\n%s\n</scene>\n'
                     % (materials(), LIGHTS, "\n".join(cams), "\n".join(insts)))
    out = S.WORK / "ui"
    if out.exists():
        import shutil
        shutil.rmtree(out)
    r = subprocess.run([S.SCENER, "--render", str(scene), "--format", "png", "--output-dir", str(out),
                        "--transparent"], capture_output=True, text=True)
    if r.returncode:
        sys.exit("scener failed on %s:\n%s" % (scene, r.stderr or r.stdout))
    # one column, each part below the last
    width = max(size[0] for _, _, size, _, _ in PARTS)
    height = sum(size[1] for _, _, size, _, _ in PARTS)
    sheet = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    meta, y = {"parts": {}}, 0
    for name, _, size, slice_px, _ in PARTS:
        img = Image.open(out / (name + ".png")).convert("RGBA").resize(size, Image.LANCZOS)
        # hard alpha: the game has a colour key, not translucency
        img.putalpha(img.getchannel("A").point(lambda a: 255 if a >= 128 else 0))
        sheet.paste(img, (0, y))
        meta["parts"][name] = [0, y, size[0], size[1], slice_px]
        y += size[1]
    S.OUT.mkdir(exist_ok=True)
    sheet.save(S.OUT / "ui.png")
    (S.OUT / "ui.json").write_text(json.dumps(meta, indent=1) + "\n")
    print("wrote %d interface parts into %s" % (len(PARTS), S.OUT / "ui.png"))


if __name__ == "__main__":
    main()
