#!/usr/bin/env python3
"""Rustfront's text faces: assets/font_body.pcx and assets/font_head.pcx, with their metrics in
assets/font.txt.

Each face is printable ASCII (32..126) in a grid of 16 x 6 equal cells, rendered from Aileron,
the CC0 (public domain) sans that Pillow bundles as its default FreeType font, so the game ships
no third-party font file and needs no system font. Coverage is kept to four levels of grey
(palette indices 1..4 of the sheet, 0 transparent); the menus tint them to their ink.

    python3 games/rustfront/art/font.py

The output depends only on the Pillow version's bundled font (it is committed, so the game
builds without Pillow).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(os.path.dirname(HERE), "assets")
FIRST, LAST, COLUMNS = 32, 126, 16
FACES = [("body", 12), ("head", 20)]
LEVELS = [0, 1, 2, 3, 4]  # transparent, then four greys, darkest first


def face(name, size):
    font = ImageFont.load_default(size)
    ascent, descent = font.getmetrics()
    cell_h = ascent + descent
    widths = []
    for c in range(FIRST, LAST + 1):
        widths.append(max(1, int(round(font.getlength(chr(c))))))
    cell_w = max(widths) + 2
    rows = (LAST - FIRST + COLUMNS) // COLUMNS
    sheet = Image.new("P", (COLUMNS * cell_w, rows * cell_h), 0)
    grey = [0, 0, 0, 96, 96, 96, 150, 150, 150, 205, 205, 205, 255, 255, 255]
    sheet.putpalette(grey + [0] * (768 - len(grey)))
    for i, c in enumerate(range(FIRST, LAST + 1)):
        glyph = Image.new("L", (cell_w, cell_h), 0)
        ImageDraw.Draw(glyph).text((0, 0), chr(c), font=font, fill=255)
        ox, oy = (i % COLUMNS) * cell_w, (i // COLUMNS) * cell_h
        src = glyph.load()
        dst = sheet.load()
        for y in range(cell_h):
            for x in range(cell_w):
                v = src[x, y]
                # Four steps of coverage; faint fringes drop out so small text stays crisp.
                dst[ox + x, oy + y] = 0 if v < 48 else 1 if v < 112 else 2 if v < 176 else 3 if v < 232 else 4
    out = os.path.join(ASSETS, "font_%s.pcx" % name)
    sheet.save(out)
    return "face %s %d %d %d %s" % (name, cell_w, cell_h, ascent, " ".join(str(w) for w in widths))


def main():
    os.makedirs(ASSETS, exist_ok=True)
    lines = ["# GENERATED by art/font.py: face NAME CELL_W CELL_H ASCENT ADVANCE[32..126]"]
    for name, size in FACES:
        lines.append(face(name, size))
    with open(os.path.join(ASSETS, "font.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote assets/font_body.pcx, assets/font_head.pcx, assets/font.txt")
    return 0


if __name__ == "__main__":
    sys.exit(main())
