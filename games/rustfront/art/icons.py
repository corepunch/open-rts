#!/usr/bin/env python3
"""Renders the sidebar's build icons (cameos) with Scener: games/rustfront/sprites/icons.png.

    python3 games/rustfront/art/icons.py

Every unit stands alone in a three-quarter hero view (yaw ICON_YAW, elevation ICON_ELEV) under
the game's lights, framed automatically from its bounds (scener --query) and rendered at
SUPERSAMPLE times the icon size, then reduced onto a bevelled steel panel. Team parts are the
default blue; art/pack8.py maps the strip onto the game palette (assets/icons.bmp).
"""
import json
import math
import subprocess
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ART = Path(__file__).resolve().parent
sys.path.insert(0, str(ART))
import layout as L  # noqa: E402
import sprites as S  # noqa: E402

ICON_W, ICON_H = 64, 48
SUPERSAMPLE = 4
ICON_YAW, ICON_ELEV = 35.0, 28.0
MARGIN = 0.10
SPACING = 3000.0

# Icon order is the strip order; the game finds an icon by its unit name.
ICONS = [
    ("power", "buildings/power", ""), ("barracks", "buildings/barracks", ""),
    ("refinery", "buildings/refinery", ""), ("factory", "buildings/factory", ""),
    ("turret", "buildings/turret", ""), ("hq", "buildings/hq", ""),
    ("rifleman", "infantry/rifleman", ' rot="-90 125 0" pose="Aim"'),
    ("rocket", "infantry/rocket", ' rot="-90 125 0" pose="Aim"'),
    ("scout", "vehicles/scout", ' rot="0 -150 0"'), ("tank", "vehicles/tank", ' rot="0 -150 0"'),
    ("apc", "vehicles/apc", ' rot="0 -150 0"'), ("artillery", "vehicles/artillery", ' rot="0 -150 0"'),
    ("harvester", "vehicles/harvester", ' rot="0 -150 0"'),
]


def basis(yaw, elev):
    a, e = math.radians(yaw), math.radians(elev)
    to_cam = (math.sin(a) * math.cos(e), math.sin(e), math.cos(a) * math.cos(e))
    right = (math.cos(a), 0.0, -math.sin(a))
    up = (-math.sin(e) * math.sin(a), math.cos(e), -math.sin(e) * math.cos(a))
    return to_cam, right, up


def scene(cams, team):
    insts = "".join('  <prefab source="%s" name="icon_%s" pos="%.1f 0 0"%s color="%s"/>\n'
                    % (src, key, i * SPACING, attrs, team) for i, (key, src, attrs) in enumerate(ICONS))
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<!-- GENERATED by icons.py -->\n'
            '<scene %s background="0 0 0">\n%s\n%s\n\n%s\n\n%s</scene>\n'
            % (L.SCENE_ATTRS, L.PALETTE.replace("{TEAM}", team), L.LIGHTS, "\n".join(cams), insts))


def panel():
    """The cameo's backing: dark steel, lighter at the top, with a bevel."""
    img = Image.new("RGB", (ICON_W, ICON_H))
    d = ImageDraw.Draw(img)
    for y in range(ICON_H):
        t = y / (ICON_H - 1)
        d.line([(0, y), (ICON_W, y)], fill=tuple(round(a + (b - a) * t) for a, b in zip((58, 62, 64), (26, 28, 30))))
    d.line([(0, 0), (ICON_W - 1, 0)], fill=(110, 114, 112))
    d.line([(0, 0), (0, ICON_H - 1)], fill=(96, 100, 98))
    d.line([(0, ICON_H - 1), (ICON_W - 1, ICON_H - 1)], fill=(10, 10, 10))
    d.line([(ICON_W - 1, 0), (ICON_W - 1, ICON_H - 1)], fill=(14, 14, 14))
    return img


def main():
    S.prepare_work()
    to_cam, right, up = basis(ICON_YAW, ICON_ELEV)
    dummy = ['  <camera name="Query" pos="0 3000 3000" look="0 0 0" ortho="1000" size="64 48"/>']
    path = S.WORK / "icons.blks"
    path.write_text(scene(dummy, L.TEAM))
    q = json.loads(subprocess.run([S.SCENER, "--query", str(path)], capture_output=True, text=True, check=True).stdout)
    bounds = {}
    def walk(n):
        if isinstance(n, dict):
            if str(n.get("name", "")).startswith("icon_") and "bounds" in n:
                bounds[n["name"][5:]] = n["bounds"]
            for v in n.values():
                walk(v)
        elif isinstance(n, list):
            for v in n:
                walk(v)
    walk(q)
    missing = [k for k, _, _ in ICONS if k not in bounds]
    if missing:
        sys.exit("icons.py: no bounds from scener --query for %s" % ", ".join(missing))

    cams = []
    for key, _, _ in ICONS:
        b = bounds[key]
        lo, hi = b["min"], b["max"]
        corners = [(x, y, z) for x in (lo[0], hi[0]) for y in (lo[1], hi[1]) for z in (lo[2], hi[2])]
        sx = [S.dot(c, right) for c in corners]
        sy = [S.dot(c, up) for c in corners]
        cx, cy = (min(sx) + max(sx)) / 2, (min(sy) + max(sy)) / 2
        w, h = (max(sx) - min(sx)) * (1 + 2 * MARGIN), (max(sy) - min(sy)) * (1 + 2 * MARGIN)
        ortho = max(h, w * ICON_H / ICON_W)
        centre = [(lo[i] + hi[i]) / 2 for i in range(3)]
        # Look at the screen-space centre of the bounds, on the plane through the 3D centre.
        dc = (cx - S.dot(centre, right), cy - S.dot(centre, up))
        look = [centre[i] + right[i] * dc[0] + up[i] * dc[1] for i in range(3)]
        pos = [look[i] + 5000 * to_cam[i] for i in range(3)]
        f = lambda v: " ".join("%.2f" % c for c in v)
        cams.append('  <camera name="%s" pos="%s" look="%s" ortho="%.2f" size="%d %d"/>'
                    % (key, f(pos), f(look), ortho, ICON_W * SUPERSAMPLE, ICON_H * SUPERSAMPLE))
    path.write_text(scene(cams, L.TEAM))
    out = S.WORK / "icons"
    S.render(path, out)
    strip = Image.new("RGB", (ICON_W * len(ICONS), ICON_H))
    for i, (key, _, _) in enumerate(ICONS):
        art = Image.open(out / ("%s.png" % key)).convert("RGBA").resize((ICON_W, ICON_H), Image.LANCZOS)
        cell = panel()
        cell.paste(art, (0, 0), art)
        strip.paste(cell, (i * ICON_W, 0))
    S.OUT.mkdir(exist_ok=True)
    strip.save(S.OUT / "icons.png", optimize=True)
    (S.OUT / "icons.json").write_text(json.dumps(dict(size=[ICON_W, ICON_H], order=[k for k, _, _ in ICONS]), indent=1) + "\n")
    print("wrote %s (%d icons)" % (S.OUT / "icons.png", len(ICONS)))


if __name__ == "__main__":
    main()
